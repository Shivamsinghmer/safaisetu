export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  let s = locale === "hi" ? (HI[key] ?? key) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const STATUS_EN: Record<TicketStatus, string> = {
  submitted: "Submitted",
  assigned: "Assigned",
  in_progress: "In progress",
  resolved: "Resolved",
  closed: "Closed",
  reopened: "Reopened",
  rejected: "Rejected",
};
const SEVERITY_EN: Record<Severity, string> = { low: "Low", medium: "Medium", high: "High" };

export const statusText = (locale: Locale, s: TicketStatus) => translate(locale, STATUS_EN[s]);
export const severityText = (locale: Locale, s: Severity) => translate(locale, SEVERITY_EN[s]);
export const categoryText = (locale: Locale, value: string) =>
  translate(locale, CATEGORY_LABELS_EN[value] ?? value.replaceAll("_", " "));

export function isLocale(v: unknown): v is Locale {
  return v === "en" || v === "hi";
}
